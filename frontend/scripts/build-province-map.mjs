// Builds src/chat/charts/provinceShapes.ts: one SVG outline per province and territory, for
// the province/territory map (#82). Run once when the outlines need to change, not on every
// build:
//
//   node scripts/build-province-map.mjs path/to/ne_50m_admin_1_states_provinces.shp
//
// Source: Natural Earth's 1:50m "Admin 1 - States, Provinces" (public domain),
// https://www.naturalearthdata.com/downloads/50m-cultural-vectors/. Detailed enough for a
// country-wide overview; too coarse for anything below province level, which this map
// doesn't do. Projected to Statistics Canada's Lambert conformal conic (EPSG:3347), as
// StatCan's own maps are, simplified, and with tiny islands dropped.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

const input = process.argv[2]
if (!input) {
  console.error(
    'Usage: node scripts/build-province-map.mjs <ne_50m_admin_1_states_provinces.shp>',
  )
  process.exit(1)
}

const STATCAN_LAMBERT =
  '+proj=lcc +lat_1=49 +lat_2=77 +lat_0=63.390675 +lon_0=-91.86666666666666 ' +
  '+x_0=6200000 +y_0=3000000 +datum=NAD83 +units=m'

const svg = execFileSync(
  'npx',
  [
    '-y',
    'mapshaper@0.6',
    input,
    '-filter',
    "admin === 'Canada'",
    '-proj',
    STATCAN_LAMBERT,
    '-simplify',
    '6%',
    'keep-shapes',
    '-filter-slivers',
    'min-area=200km2',
    '-o',
    'format=svg',
    'id-field=postal',
    'width=600',
    'precision=0.1',
    '-',
  ],
  { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 },
)

const viewBox = svg.match(/viewBox="([^"]+)"/)[1]
// Attribute order varies (multi-part provinces get a fill-rule), so read each path's
// attributes separately.
const shapes = [...svg.matchAll(/<path\b[^>]*>/g)].map(([tag]) => [
  tag.match(/\bid="([A-Z]{2})"/)[1],
  tag
    .match(/\bd="([^"]+)"/)[1]
    .replace(/\s+/g, ' ')
    .trim(),
])
if (shapes.length !== 13)
  throw new Error(`Expected 13 provinces and territories, got ${shapes.length}`)

writeFileSync(
  new URL('../src/chat/charts/provinceShapes.ts', import.meta.url),
  `// Generated by scripts/build-province-map.mjs from Natural Earth (public domain) - don't edit.
import type { ProvinceCode } from './provinces'

export const MAP_VIEWBOX = '${viewBox}'

export const PROVINCE_SHAPES: Record<ProvinceCode, string> = {
${shapes.map(([code, d]) => `  ${code}: '${d}',`).join('\n')}
}
`,
)
console.log(`Wrote ${shapes.length} outlines`)
